export const pauseSeconds = [24,10,12,10,12,16,14,14,10,22,14,22];

export function mountSpeakerNotes() {
  document.querySelectorAll(".slide").forEach((slide,index)=>{
    const paragraphs = speakerNotes[index];
    const words = paragraphs.join(" ").split(/\s+/u).length;
    const seconds = Math.round(words / 110 * 60 + pauseSeconds[index]);
    slide.dataset.duration = String(seconds);
    slide.querySelector(".speaker-notes").innerHTML = `<p class="note-timing">${Math.floor(seconds/60)}:${String(seconds%60).padStart(2,"0")} aprox. · lectura a 110 palabras/min + pausas</p>` + paragraphs.map(p=>`<p>${p}</p>`).join("");
  });
}
